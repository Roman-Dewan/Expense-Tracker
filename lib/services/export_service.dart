enum ExportFormat { pdf, excel, csv }

class ExportResult {
  final bool success;
  final String? filePath;
  final String? fileName;
  final String? message;

  const ExportResult({
    required this.success,
    this.filePath,
    this.fileName,
    this.message,
  });
}

class ExportService {
  static final ExportService instance = ExportService._internal();
  ExportService._internal();

  /// Main export entry point - saves file directly to device storage without sharing
  Future<ExportResult> exportMonthTransactions({
    required DateTime month,
    required List<Transaction> transactions,
    required List<Category> categories,
    required List<Account> accounts,
    required ExportFormat format,
  }) async {
    if (transactions.isEmpty) {
      return const ExportResult(
        success: false,
        message: 'No transactions found for the selected month.',
      );
    }

    final monthStr = DateFormat('yyyy_MM').format(month);
    final monthDisplay = DateFormat('MMMM yyyy').format(month);

    final categoryMap = {for (var c in categories) c.id: c.name};
    final accountMap = {for (var a in accounts) a.id: a.name};

    Uint8List bytes;
    String filename;

    switch (format) {
      case ExportFormat.pdf:
        filename = 'Expense_Report_$monthStr.pdf';
        bytes = await _generatePdfBytes(
          monthDisplay: monthDisplay,
          transactions: transactions,
          categoryMap: categoryMap,
          accountMap: accountMap,
        );
        break;
      case ExportFormat.excel:
        filename = 'Expense_Report_$monthStr.xlsx';
        bytes = await _generateExcelBytes(
          monthDisplay: monthDisplay,
          transactions: transactions,
          categoryMap: categoryMap,
          accountMap: accountMap,
        );
        break;
      case ExportFormat.csv:
        filename = 'Expense_Report_$monthStr.csv';
        bytes = await _generateCsvBytes(
          transactions: transactions,
          categoryMap: categoryMap,
          accountMap: accountMap,
        );
        break;
    }

    return await _saveBytesToDeviceStorage(
      bytes: bytes,
      filename: filename,
      format: format,
    );
  }

  /// Saves the generated bytes directly to the device storage
  Future<ExportResult> _saveBytesToDeviceStorage({
    required Uint8List bytes,
    required String filename,
    required ExportFormat format,
  }) async {
    // 1. Always keep a backup copy in the app document storage
    try {
      final docDir = await getApplicationDocumentsDirectory();
      final localCopy = File('${docDir.path}/$filename');
      await localCopy.writeAsBytes(bytes, flush: true);
    } catch (e) {
      debugPrint('Local cache write note: $e');
    }

    // 2. Direct save to public Download directory if accessible
    if (Platform.isAndroid) {
      try {
        final downloadDir = Directory('/storage/emulated/0/Download');
        if (await downloadDir.exists()) {
          final targetFile = File('${downloadDir.path}/$filename');
          await targetFile.writeAsBytes(bytes, flush: true);
          return ExportResult(
            success: true,
            filePath: targetFile.path,
            fileName: filename,
            message: 'Saved to Download folder',
          );
        }
      } catch (e) {
        debugPrint('Direct write to Android Download folder failed ($e), attempting SAF.');
      }
    } else if (Platform.isWindows) {
      // Windows Desktop Downloads folder
      try {
        final userProfile = Platform.environment['USERPROFILE'];
        if (userProfile != null) {
          final downloadDir = Directory('$userProfile\\Downloads');
          if (await downloadDir.exists()) {
            final targetFile = File('${downloadDir.path}\\$filename');
            await targetFile.writeAsBytes(bytes, flush: true);
            return ExportResult(
              success: true,
              filePath: targetFile.path,
              fileName: filename,
              message: 'Saved to Downloads folder',
            );
          }
        }
      } catch (e) {
        debugPrint('Direct write to Windows Downloads failed: $e');
      }
    } else if (!Platform.isIOS) {
      // macOS, Linux
      try {
        final downloadDir = await getDownloadsDirectory();
        if (downloadDir != null && await downloadDir.exists()) {
          final targetFile = File('${downloadDir.path}${Platform.pathSeparator}$filename');
          await targetFile.writeAsBytes(bytes, flush: true);
          return ExportResult(
            success: true,
            filePath: targetFile.path,
            fileName: filename,
            message: 'Saved to Downloads folder',
          );
        }
      } catch (e) {
        debugPrint('Direct write to desktop Downloads failed: $e');
      }
    }

    // 3. Native Storage Access Framework / File Picker save dialog
    try {
      final ext = format == ExportFormat.pdf
          ? 'pdf'
          : (format == ExportFormat.excel ? 'xlsx' : 'csv');

      final mimeType = format == ExportFormat.pdf
          ? 'application/pdf'
          : (format == ExportFormat.excel
              ? 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'
              : 'text/csv');

      final pickedUri = await FilePicker.saveFile(
        dialogTitle: 'Save $filename to Device Storage',
        fileName: filename,
        bytes: bytes,
        mimeType: mimeType,
        type: FileType.custom,
        allowedExtensions: [ext],
      );

      if (pickedUri != null) {
        String savedPath;
        try {
          savedPath = pickedUri.toFilePath();
        } catch (_) {
          savedPath = pickedUri.path;
        }

        return ExportResult(
          success: true,
          filePath: savedPath,
          fileName: filename,
          message: 'Saved to device storage',
        );
      } else {
        return const ExportResult(
          success: false,
          message: 'Export cancelled by user',
        );
      }
    } catch (e) {
      debugPrint('FilePicker saveFile fallback: $e');
    }

    // 4. Fallback: app external/documents storage
    try {
      Directory? targetDir;
      if (Platform.isAndroid) {
        final extDirs = await getExternalStorageDirectories(type: StorageDirectory.downloads);
        if (extDirs != null && extDirs.isNotEmpty) {
          targetDir = extDirs.first;
        }
      }
      targetDir ??= await getApplicationDocumentsDirectory();

      final targetFile = File('${targetDir.path}/$filename');
      await targetFile.writeAsBytes(bytes, flush: true);

      return ExportResult(
        success: true,
        filePath: targetFile.path,
        fileName: filename,
        message: 'Saved to storage: ${targetFile.path}',
      );
    } catch (e) {
      return ExportResult(
        success: false,
        message: 'Failed to save file: $e',
      );
    }
  }

  // ================= 1. PDF GENERATOR ================= //
  Future<Uint8List> _generatePdfBytes({
    required String monthDisplay,
    required List<Transaction> transactions,
    required Map<String, String> categoryMap,
    required Map<String, String> accountMap,
  }) async {
    final pdf = pw.Document();

    double totalIncome = 0.0;
    double totalExpense = 0.0;

    final categoryTotals = <String, double>{};

    for (final tx in transactions) {
      if (tx.type == TransactionType.income) {
        totalIncome += tx.amount;
      } else if (tx.type == TransactionType.expense) {
        totalExpense += tx.amount;
        final catName = categoryMap[tx.categoryId] ?? 'Uncategorized';
        categoryTotals[catName] = (categoryTotals[catName] ?? 0) + tx.amount;
      }
    }

    final netSavings = totalIncome - totalExpense;
    final savingsRate = totalIncome > 0
        ? ((netSavings / totalIncome) * 100).clamp(-100.0, 100.0)
        : 0.0;

    final dateFormat = DateFormat('yyyy-MM-dd');
    final currencyFormat = NumberFormat.currency(symbol: 'BDT ', decimalDigits: 0);

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        header: (context) {
          return pw.Container(
            padding: const pw.EdgeInsets.only(bottom: 16),
            decoration: const pw.BoxDecoration(
              border: pw.Border(
                bottom: pw.BorderSide(color: PdfColors.grey300, width: 1),
              ),
            ),
            child: pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: [
                    pw.Text(
                      'MONTHLY EXPENSE STATEMENT',
                      style: pw.TextStyle(
                        fontSize: 18,
                        fontWeight: pw.FontWeight.bold,
                        color: PdfColors.indigo900,
                      ),
                    ),
                    pw.SizedBox(height: 4),
                    pw.Text(
                      'Period: $monthDisplay',
                      style: const pw.TextStyle(
                        fontSize: 12,
                        color: PdfColors.grey700,
                      ),
                    ),
                  ],
                ),
                pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.end,
                  children: [
                    pw.Text(
                      'Generated: ${DateFormat('yyyy-MM-dd HH:mm').format(DateTime.now())}',
                      style: const pw.TextStyle(
                        fontSize: 10,
                        color: PdfColors.grey600,
                      ),
                    ),
                    pw.Text(
                      'Total Records: ${transactions.length}',
                      style: pw.TextStyle(
                        fontSize: 10,
                        fontWeight: pw.FontWeight.bold,
                        color: PdfColors.grey800,
                      ),
                    ),
                  ],
                ),
              ],
            ),
          );
        },
        build: (context) => [
          pw.SizedBox(height: 16),
          // KPI Metric Cards
          pw.Row(
            children: [
              _buildPdfKpiCard(
                'Total Income',
                currencyFormat.format(totalIncome),
                PdfColors.green800,
                PdfColors.green50,
              ),
              pw.SizedBox(width: 12),
              _buildPdfKpiCard(
                'Total Expenses',
                currencyFormat.format(totalExpense),
                PdfColors.red800,
                PdfColors.red50,
              ),
              pw.SizedBox(width: 12),
              _buildPdfKpiCard(
                'Net Savings',
                currencyFormat.format(netSavings),
                netSavings >= 0 ? PdfColors.blue800 : PdfColors.red800,
                PdfColors.blue50,
              ),
              pw.SizedBox(width: 12),
              _buildPdfKpiCard(
                'Savings Rate',
                '${savingsRate.toStringAsFixed(1)}%',
                PdfColors.purple800,
                PdfColors.purple50,
              ),
            ],
          ),
          pw.SizedBox(height: 20),

          // Category summary
          if (categoryTotals.isNotEmpty) ...[
            pw.Text(
              'Expense Category Breakdown',
              style: pw.TextStyle(fontSize: 14, fontWeight: pw.FontWeight.bold),
            ),
            pw.SizedBox(height: 8),
            pw.Table(
              border: pw.TableBorder.all(color: PdfColors.grey200, width: 0.5),
              children: [
                pw.TableRow(
                  decoration: const pw.BoxDecoration(color: PdfColors.grey100),
                  children: [
                    _tableCell('Category', isHeader: true),
                    _tableCell('Amount', isHeader: true, alignRight: true),
                    _tableCell('% of Expense', isHeader: true, alignRight: true),
                  ],
                ),
                ...categoryTotals.entries.map((entry) {
                  final pct = totalExpense > 0
                      ? (entry.value / totalExpense) * 100
                      : 0.0;
                  return pw.TableRow(
                    children: [
                      _tableCell(entry.key),
                      _tableCell(
                        currencyFormat.format(entry.value),
                        alignRight: true,
                      ),
                      _tableCell('${pct.toStringAsFixed(1)}%', alignRight: true),
                    ],
                  );
                }),
              ],
            ),
            pw.SizedBox(height: 20),
          ],

          // Transactions Table
          pw.Text(
            'Itemized Transactions Ledger',
            style: pw.TextStyle(fontSize: 14, fontWeight: pw.FontWeight.bold),
          ),
          pw.SizedBox(height: 8),
          pw.Table(
            border: pw.TableBorder.all(color: PdfColors.grey200, width: 0.5),
            children: [
              pw.TableRow(
                decoration: const pw.BoxDecoration(color: PdfColors.indigo50),
                children: [
                  _tableCell('Date', isHeader: true),
                  _tableCell('Title / Description', isHeader: true),
                  _tableCell('Category', isHeader: true),
                  _tableCell('Account', isHeader: true),
                  _tableCell('Type', isHeader: true),
                  _tableCell('Amount', isHeader: true, alignRight: true),
                ],
              ),
              ...transactions.map((tx) {
                final isExp = tx.type == TransactionType.expense;
                final isInc = tx.type == TransactionType.income;
                final typeStr = tx.type.name.toUpperCase();
                final catStr = categoryMap[tx.categoryId] ?? '-';
                final accStr = accountMap[tx.accountId] ?? 'Cash';

                return pw.TableRow(
                  children: [
                    _tableCell(dateFormat.format(tx.date)),
                    _tableCell(tx.title),
                    _tableCell(catStr),
                    _tableCell(accStr),
                    _tableCell(typeStr),
                    _tableCell(
                      '${isExp ? "-" : (isInc ? "+" : "")} ${currencyFormat.format(tx.amount)}',
                      alignRight: true,
                      textColor: isExp
                          ? PdfColors.red800
                          : (isInc ? PdfColors.green800 : PdfColors.blue800),
                    ),
                  ],
                );
              }),
            ],
          ),
        ],
        footer: (context) {
          return pw.Container(
            alignment: pw.Alignment.centerRight,
            margin: const pw.EdgeInsets.only(top: 16),
            child: pw.Text(
              'Page ${context.pageNumber} of ${context.pagesCount}',
              style: const pw.TextStyle(color: PdfColors.grey600, fontSize: 10),
            ),
          );
        },
      ),
    );

    return await pdf.save();
  }

  pw.Widget _buildPdfKpiCard(
    String title,
    String value,
    PdfColor textColor,
    PdfColor bgColor,
  ) {
    return pw.Expanded(
      child: pw.Container(
        padding: const pw.EdgeInsets.all(10),
        decoration: pw.BoxDecoration(
          color: bgColor,
          borderRadius: pw.BorderRadius.circular(6),
          border: pw.Border.all(color: textColor, width: 0.5),
        ),
        child: pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Text(
              title,
              style: pw.TextStyle(color: PdfColors.grey700, fontSize: 9),
            ),
            pw.SizedBox(height: 4),
            pw.Text(
              value,
              style: pw.TextStyle(
                color: textColor,
                fontSize: 13,
                fontWeight: pw.FontWeight.bold,
              ),
            ),
          ],
        ),
      ),
    );
  }

  pw.Widget _tableCell(
    String text, {
    bool isHeader = false,
    bool alignRight = false,
    PdfColor? textColor,
  }) {
    return pw.Padding(
      padding: const pw.EdgeInsets.symmetric(vertical: 6, horizontal: 8),
      child: pw.Align(
        alignment: alignRight ? pw.Alignment.centerRight : pw.Alignment.centerLeft,
        child: pw.Text(
          text,
          style: pw.TextStyle(
            fontSize: 9,
            fontWeight: isHeader ? pw.FontWeight.bold : pw.FontWeight.normal,
            color: textColor ?? (isHeader ? PdfColors.grey900 : PdfColors.grey800),
          ),
        ),
      ),
    );
  }

  // ================= 2. EXCEL GENERATOR ================= //
  Future<Uint8List> _generateExcelBytes({
    required String monthDisplay,
    required List<Transaction> transactions,
    required Map<String, String> categoryMap,
    required Map<String, String> accountMap,
  }) async {
    final excel = xl.Excel.createExcel();

    // 1. Transactions Sheet
    const sheetName = 'Transactions';
    final sheet = excel[sheetName];
    excel.setDefaultSheet(sheetName);

    // Header Row
    final headers = [
      'Transaction ID',
      'Date',
      'Title',
      'Type',
      'Category',
      'Account',
      'Amount',
      'Notes',
    ];
    sheet.appendRow(headers.map((h) => xl.TextCellValue(h)).toList());

    for (final tx in transactions) {
      final catStr = categoryMap[tx.categoryId] ?? 'Uncategorized';
      final accStr = accountMap[tx.accountId] ?? 'Cash';
      sheet.appendRow([
        xl.TextCellValue(tx.id),
        xl.TextCellValue(DateFormat('yyyy-MM-dd HH:mm').format(tx.date)),
        xl.TextCellValue(tx.title),
        xl.TextCellValue(tx.type.name.toUpperCase()),
        xl.TextCellValue(catStr),
        xl.TextCellValue(accStr),
        xl.IntCellValue(tx.amount.round()),
        xl.TextCellValue(tx.notes ?? ''),
      ]);
    }

    // 2. Summary Sheet
    final summarySheet = excel['Monthly Summary'];
    summarySheet.appendRow([
      xl.TextCellValue('Metric'),
      xl.TextCellValue('Value'),
    ]);

    double totalIncome = 0.0;
    double totalExpense = 0.0;
    for (final tx in transactions) {
      if (tx.type == TransactionType.income) totalIncome += tx.amount;
      if (tx.type == TransactionType.expense) totalExpense += tx.amount;
    }

    summarySheet.appendRow([
      xl.TextCellValue('Period'),
      xl.TextCellValue(monthDisplay),
    ]);
    summarySheet.appendRow([
      xl.TextCellValue('Total Income (BDT)'),
      xl.IntCellValue(totalIncome.round()),
    ]);
    summarySheet.appendRow([
      xl.TextCellValue('Total Expenses (BDT)'),
      xl.IntCellValue(totalExpense.round()),
    ]);
    summarySheet.appendRow([
      xl.TextCellValue('Net Savings (BDT)'),
      xl.IntCellValue((totalIncome - totalExpense).round()),
    ]);
    summarySheet.appendRow([
      xl.TextCellValue('Total Transactions'),
      xl.IntCellValue(transactions.length),
    ]);

    final bytes = excel.encode();
    if (bytes == null) {
      throw Exception('Failed to generate Excel file.');
    }
    return Uint8List.fromList(bytes);
  }

  // ================= 3. CSV GENERATOR ================= //
  Future<Uint8List> _generateCsvBytes({
    required List<Transaction> transactions,
    required Map<String, String> categoryMap,
    required Map<String, String> accountMap,
  }) async {
    final rows = <List<dynamic>>[];

    // Header
    rows.add([
      'Transaction ID',
      'Date',
      'Title',
      'Type',
      'Category',
      'Account',
      'Amount',
      'Notes',
    ]);

    for (final tx in transactions) {
      final catStr = categoryMap[tx.categoryId] ?? 'Uncategorized';
      final accStr = accountMap[tx.accountId] ?? 'Cash';
      rows.add([
        tx.id,
        DateFormat('yyyy-MM-dd HH:mm:ss').format(tx.date),
        tx.title,
        tx.type.name.toUpperCase(),
        catStr,
        accStr,
        tx.amount.round().toString(),
        tx.notes ?? '',
      ]);
    }

    final csvData = csv.encode(rows);
    return Uint8List.fromList(utf8.encode(csvData));
  }
}
